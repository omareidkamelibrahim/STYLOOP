import { jsonb, pgTable, text, timestamp, uuid, integer, numeric, date } from "drizzle-orm/pg-core"

export const quoteRequests = pgTable("quote_requests", {
  id: uuid("id").defaultRandom().primaryKey(),
  reference: text("reference").notNull().unique(),
  userId: text("user_id"),
  customerName: text("customer_name").notNull(),
  email: text("email").notNull(),
  phone: text("phone"),
  companyName: text("company_name"),
  garmentType: text("garment_type").notNull(),
  garmentColor: text("garment_color"),
  sizes: jsonb("sizes").$type<Record<string, number>>().notNull(),
  quantity: integer("quantity").notNull(),
  designCount: integer("design_count").notNull(),
  printingLocations: text("printing_locations").array().notNull(),
  printingMethod: text("printing_method"),
  artworkUrls: text("artwork_urls").array().notNull(),
  instructions: text("instructions"),
  requiredDeliveryDate: date("required_delivery_date", { mode: "string" }),
  deliveryLocation: text("delivery_location"),
  status: text("status").notNull().default("new"),
  quoteAmount: numeric("quote_amount", { precision: 12, scale: 2 }),
  currency: text("currency").notNull().default("USD"),
  quoteValidUntil: date("quote_valid_until", { mode: "string" }),
  adminNotes: text("admin_notes"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
})
